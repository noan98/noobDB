import { describe, expect, it } from "vitest";
import type { TableColumnInfo } from "../api/tauri";
import {
  buildCreateTableSql,
  columnDefsFromTableInfo,
  templateCaveats,
  formatDefault,
  type ColumnDef,
} from "../components/createTable";

const col = (over: Partial<ColumnDef>): ColumnDef => ({
  name: "c",
  type: "TEXT",
  notNull: false,
  primaryKey: false,
  unique: false,
  autoIncrement: false,
  defaultValue: "",
  ...over,
});

describe("formatDefault", () => {
  it("returns null for empty", () => {
    expect(formatDefault("mysql", "  ")).toBeNull();
  });
  it("passes through numbers and known keywords", () => {
    expect(formatDefault("mysql", "42")).toBe("42");
    expect(formatDefault("mysql", "-1.5")).toBe("-1.5");
    expect(formatDefault("postgres", "current_timestamp")).toBe("CURRENT_TIMESTAMP");
    expect(formatDefault("sqlite", "null")).toBe("NULL");
  });
  it("quotes other values as string literals", () => {
    expect(formatDefault("mysql", "hello")).toBe("'hello'");
    expect(formatDefault("postgres", "O'Brien")).toBe("'O''Brien'");
  });
});

describe("buildCreateTableSql", () => {
  it("builds a MySQL table with auto-increment PK and backtick idents", () => {
    const sql = buildCreateTableSql("mysql", {
      database: "shop",
      table: "users",
      columns: [
        col({ name: "id", type: "INT", primaryKey: true, autoIncrement: true, notNull: true }),
        col({ name: "email", type: "VARCHAR(255)", notNull: true, unique: true }),
      ],
    });
    expect(sql).toContain("CREATE TABLE `shop`.`users`");
    expect(sql).toContain("`id` INT NOT NULL AUTO_INCREMENT");
    expect(sql).toContain("`email` VARCHAR(255) NOT NULL UNIQUE");
    expect(sql).toContain("PRIMARY KEY (`id`)");
  });

  it("uses double-quote idents and IDENTITY for PostgreSQL", () => {
    const sql = buildCreateTableSql("postgres", {
      database: "public",
      table: "t",
      columns: [col({ name: "id", type: "BIGINT", primaryKey: true, autoIncrement: true })],
    });
    expect(sql).toContain('CREATE TABLE "public"."t"');
    expect(sql).toContain('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('PRIMARY KEY ("id")');
  });

  it("emits SQLite INTEGER PRIMARY KEY AUTOINCREMENT inline (no table-level PK)", () => {
    const sql = buildCreateTableSql("sqlite", {
      table: "t",
      columns: [
        col({ name: "id", type: "INTEGER", primaryKey: true, autoIncrement: true }),
        col({ name: "label", type: "TEXT", notNull: true }),
      ],
    });
    expect(sql).toContain('CREATE TABLE "t"');
    expect(sql).toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
    expect(sql).not.toContain("PRIMARY KEY (");
    expect(sql).toContain('"label" TEXT NOT NULL');
  });

  it("supports a composite primary key", () => {
    const sql = buildCreateTableSql("mysql", {
      table: "t",
      columns: [
        col({ name: "a", type: "INT", primaryKey: true }),
        col({ name: "b", type: "INT", primaryKey: true }),
      ],
    });
    expect(sql).toContain("PRIMARY KEY (`a`, `b`)");
  });

  it("escapes a string DEFAULT", () => {
    const sql = buildCreateTableSql("mysql", {
      table: "t",
      columns: [col({ name: "status", type: "VARCHAR(20)", defaultValue: "active" })],
    });
    expect(sql).toContain("`status` VARCHAR(20) DEFAULT 'active'");
  });

  it("omits the database qualifier for SQLite", () => {
    const sql = buildCreateTableSql("sqlite", {
      database: "ignored",
      table: "t",
      columns: [col({ name: "x", type: "TEXT" })],
    });
    expect(sql).toContain('CREATE TABLE "t"');
    expect(sql).not.toContain("ignored");
  });
});

describe("formatDefault: 型と式の判定 (#1527)", () => {
  it("文字列型の数値風既定値は先頭ゼロを保つため文字列リテラルにする", () => {
    for (const d of ["mysql", "postgres", "sqlite"]) {
      expect(formatDefault(d, "007", "VARCHAR(10)")).toBe("'007'");
      expect(formatDefault(d, "007", "INT")).toBe("007");
      expect(formatDefault(d, "1.5", "numeric(8,2)")).toBe("1.5");
      expect(formatDefault(d, "true", "VARCHAR(10)")).toBe("'true'");
      expect(formatDefault(d, "true", "BOOLEAN")).toBe("TRUE");
    }
  });
  it("関数呼び出し・括弧式・キャストは逐語で出す", () => {
    expect(formatDefault("postgres", "gen_random_uuid()::text", "text")).toBe("gen_random_uuid()::text");
    expect(formatDefault("mysql", "(UUID())", "varchar(36)")).toBe("(UUID())");
    expect(formatDefault("sqlite", "(datetime('now'))", "text")).toBe("(datetime('now'))");
    expect(formatDefault("mysql", "hello world", "varchar(36)")).toBe("'hello world'");
  });
});

describe("formatDefault: 式判定の厳密化 (#1527 レビュー)", () => {
  it("`::` を含むだけの文字列は式にしない", () => {
    expect(formatDefault("postgres", "Error::NotFound", "text")).toBe("'Error::NotFound'");
    expect(formatDefault("postgres", "fe80::abcd", "text")).toBe("'fe80::abcd'");
  });
  it("閉じた '...' は逐語 (文字列リテラルを強制できる)", () => {
    expect(formatDefault("mysql", "'(none)'", "varchar(10)")).toBe("'(none)'");
    expect(formatDefault("postgres", "'x'::text", "text")).toBe("'x'::text");
    expect(formatDefault("mysql", "it's", "varchar(10)")).toBe("'it''s'");
  });
  it("括弧なしの関数呼び出しは mysql / sqlite で括り、現在時刻系と PostgreSQL は括らない", () => {
    expect(formatDefault("mysql", "uuid()", "varchar(36)")).toBe("(uuid())");
    expect(formatDefault("sqlite", "lower(hex(randomblob(4)))", "text")).toBe("(lower(hex(randomblob(4))))");
    expect(formatDefault("postgres", "gen_random_uuid()", "uuid")).toBe("gen_random_uuid()");
    expect(formatDefault("mysql", "CURRENT_TIMESTAMP(6)", "datetime(6)")).toBe("CURRENT_TIMESTAMP(6)");
    expect(formatDefault("mysql", "now()", "datetime")).toBe("NOW()");
  });
  it("literal モードは式判定をしない", () => {
    expect(formatDefault("mysql", "(none)", "varchar(10)", { literal: true })).toBe("'(none)'");
  });
});

describe("columnDefsFromTableInfo (#1540)", () => {
  const info = (over: Partial<TableColumnInfo> & { name: string }): TableColumnInfo => ({
    data_type: "int",
    nullable: true,
    key: "",
    default: null,
    extra: "",
    referenced_table: null,
    referenced_column: null,
    ...over,
  });

  it("型・NOT NULL・主キー・UNIQUE・既定値を引き継ぐ", () => {
    const defs = columnDefsFromTableInfo([
      info({ name: "id", data_type: "bigint", nullable: false, key: "PRI", extra: "auto_increment" }),
      info({ name: "email", data_type: "varchar(255)", nullable: false, key: "UNI" }),
      info({ name: "status", data_type: "varchar(16)", default: "active" }),
      info({ name: "note", data_type: "text" }),
    ]);
    expect(defs).toEqual([
      {
        name: "id",
        type: "bigint",
        notNull: true,
        primaryKey: true,
        unique: false,
        autoIncrement: true,
        defaultValue: "",
      },
      {
        name: "email",
        type: "varchar(255)",
        notNull: true,
        primaryKey: false,
        unique: true,
        autoIncrement: false,
        defaultValue: "",
      },
      {
        name: "status",
        type: "varchar(16)",
        notNull: false,
        primaryKey: false,
        unique: false,
        autoIncrement: false,
        defaultValue: "active",
      },
      {
        name: "note",
        type: "text",
        notNull: false,
        primaryKey: false,
        unique: false,
        autoIncrement: false,
        defaultValue: "",
      },
    ]);
  });

  it("主キー列は NULL 可と報告されても NOT NULL にする (SQLite)", () => {
    const [id] = columnDefsFromTableInfo([info({ name: "id", data_type: "INTEGER", key: "PRI" })]);
    expect(id.notNull).toBe(true);
  });

  it("PostgreSQL の nextval 既定値は自動採番に写し、元のシーケンス参照を持ち越さない", () => {
    const [id] = columnDefsFromTableInfo([
      info({
        name: "id",
        data_type: "integer",
        nullable: false,
        key: "PRI",
        default: "nextval('orders_id_seq'::regclass)",
      }),
    ]);
    expect(id.autoIncrement).toBe(true);
    expect(id.defaultValue).toBe("");
  });

  it("生成列は既定値なしの通常列、DEFAULT_GENERATED の既定値は残す", () => {
    const [gen, dg] = columnDefsFromTableInfo([
      info({ name: "total", extra: "STORED GENERATED", default: "price * qty" }),
      info({
        name: "created",
        data_type: "datetime",
        extra: "DEFAULT_GENERATED",
        default: "CURRENT_TIMESTAMP",
      }),
    ]);
    expect(gen.defaultValue).toBe("");
    expect(dg.defaultValue).toBe("CURRENT_TIMESTAMP");
  });

  it("生成した雛形から 3 ドライバで CREATE TABLE が組み立つ", () => {
    const defs = columnDefsFromTableInfo([
      info({ name: "id", data_type: "int", nullable: false, key: "PRI", extra: "auto_increment" }),
      info({ name: "name", data_type: "varchar(50)", default: "x" }),
    ]);
    expect(buildCreateTableSql("mysql", { database: "d", table: "t2", columns: defs })).toBe(
      "CREATE TABLE `d`.`t2` (\n  `id` int NOT NULL AUTO_INCREMENT,\n  `name` varchar(50) DEFAULT 'x',\n  PRIMARY KEY (`id`)\n);",
    );
    expect(buildCreateTableSql("postgres", { database: "d", table: "t2", columns: defs })).toContain(
      '"id" int NOT NULL GENERATED BY DEFAULT AS IDENTITY',
    );
    expect(buildCreateTableSql("sqlite", { table: "t2", columns: defs })).toContain(
      '"id" INTEGER PRIMARY KEY AUTOINCREMENT',
    );
  });
});

describe("templateCaveats (#1540)", () => {
  const i = (name: string, over: Record<string, unknown> = {}) => ({
    name,
    data_type: "integer",
    nullable: true,
    key: "",
    default: null,
    extra: "",
    referenced_table: null,
    referenced_column: null,
    ...over,
  });
  it("PostgreSQL の USER-DEFINED / ARRAY / IDENTITY の可能性がある整数主キーを拾う", () => {
    const c = templateCaveats("postgres", [
      i("id", { key: "PRI", nullable: false }),
      i("mood", { data_type: "USER-DEFINED" }),
      i("tags", { data_type: "ARRAY" }),
      i("seq", { key: "PRI", default: "nextval('s'::regclass)" }),
    ] as never);
    expect(c).toEqual({ userDefined: ["mood"], arrays: ["tags"], identityMaybe: ["id"] });
  });
  it("PostgreSQL 以外では注記なし", () => {
    expect(templateCaveats("mysql", [i("m", { data_type: "ARRAY" })] as never)).toEqual({
      userDefined: [],
      arrays: [],
      identityMaybe: [],
    });
  });
});
