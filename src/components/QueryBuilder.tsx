// テスト (QueryBuilder.test.ts) からバックスラッシュ/クオート処理を直接検証
// できるよう export する (他の生成ロジックと違い、この関数はコンポーネント外に
// 切り出されておらずここが唯一のテスト経路)。
export function quoteValue(driver: string, raw: string): string {
  const v = raw.trim();
  if (v === "") return "''";
  if (/^null$/i.test(v)) return "NULL";
  if (/^-?\d+(\.\d+)?$/.test(v)) return v;
  if (/^(true|false)$/i.test(v)) {
    // SQLite has no native boolean literal — emit 1/0 instead of TRUE/FALSE.
    if (driver === "sqlite") return v.toLowerCase() === "true" ? "1" : "0";
    return v.toUpperCase();
  }
  // バックスラッシュの二重化は MySQL のみ必要。PostgreSQL (既定の
  // standard_conforming_strings = on)・SQLite ではバックスラッシュは
  // ただの文字なので、二重化すると値が変わってしまい (例: C:\temp が
  // C:\\temp として保存され)、WHERE 句が既存行に一致しなくなる。
  // cellEdit.ts の quoteString / db/data_diff.rs の quote_string と方針を揃える。
  const escaped = driver === "mysql" ? v.replace(/\\/g, "\\\\").replace(/'/g, "''") : v.replace(/'/g, "''");
  return "'" + escaped + "'";
}

/**
 * Column-type aware literal builder (改善 1). `quoteValue` above guesses a
 * value's shape from the text itself, which is wrong whenever the shape lies:
 * typing the digits `123` into a VARCHAR column must stay the string `'123'`,
 * not become a bare numeral. When the column's actual `TableColumnInfo` is
 * known, this trusts the declared type instead of the input text.
 *
 * Reuses `cellEdit.ts`'s type classification (`classifyEditType`) and string
 * quoting (`quoteString`) rather than re-deriving them, so the Query Builder's
 * "type → SQL literal" decision cannot drift from the inline cell editor's
 * (`literalFromInput`, not exported — this mirrors its NULL / numeric /
 * boolean rules). Callers fall back to `quoteValue` when no column metadata
 * resolved (e.g. a free-typed column name absent from `describeTable`).
 */
export function quoteValueForColumn(driver: string, raw: string, info: TableColumnInfo): string {
  const trimmed = raw.trim();
  if (/^null$/i.test(trimmed)) return "NULL";
  const kind: EditTypeKind = classifyEditType(info.data_type);
  if (kind === "number" && /^-?\d+(\.\d+)?(e[+-]?\d+)?$/i.test(trimmed)) {
    return trimmed;
  }
  if (kind === "boolean") {
    const lc = trimmed.toLowerCase();
    if (lc === "true" || lc === "1") {
      // SQLite has no native boolean literal — 1/0 instead, same convention
      // as `quoteValue` above.
      return driver === "sqlite" ? "1" : "TRUE";
    }
    if (lc === "false" || lc === "0") {
      return driver === "sqlite" ? "0" : "FALSE";
    }
  }
  // Everything else — string-like columns, and a numeric/boolean-looking
  // value that didn't match the column's actual type above — is a quoted
  // string literal. This is the correctness fix: a VARCHAR column never
  // silently turns "123" or "true" into an unquoted literal.
  return quoteString(driver, raw);
}

/** Looks up a table's column metadata by name; `undefined` for a free-typed
 *  column absent from the `describeTable` result (callers fall back to the
 *  type-agnostic `quoteValue`). */
function resolveColumnInfo(columns: TableColumnInfo[], name: string): TableColumnInfo | undefined {
  return columns.find((c) => c.name === name);
}

/**
 * Whether a NOT NULL column's edit box currently holds the literal `NULL`
 * keyword (case-insensitive) — this will fail at Apply, so the row shows an
 * inline warning (改善 1-4). Never blocks Run/Dry Run; `computeBuilderBlockedReason`
 * is the only thing that does that (改善 2).
 */
export function isNullValueOnNotNullColumn(raw: string, info: TableColumnInfo | undefined | null): boolean {
  if (!info || info.nullable) return false;
  return /^null$/i.test(raw.trim());
}

/**
 * A column INSERT genuinely can't skip (改善 2): NOT NULL, no default value,
 * and not DB-populated (`isAutoGenerated`, shared with `testDataGen.ts`'s
 * "omit auto-generated columns" rule). Used to mark INSERT pair rows with a
 * required indicator — informational only, never blocks Run (an omitted
 * required column simply fails at the server, same as today).
 */
export function isRequiredColumn(info: TableColumnInfo | undefined | null): boolean {
  if (!info) return false;
  return !info.nullable && info.default === null && !isAutoGenerated(info);
}

function tableRef(driver: string, database: string, table: string): string {
  const tbl = table ? quoteIdentFor(driver, table) : "<table>";
  // SQLite has a single namespace per connection — no database qualifier.
  if (driver === "sqlite") return tbl;
  if (database) {
    return `${quoteIdentFor(driver, database)}.${tbl}`;
  }
  return tbl;
}

/**
 * WHERE 条件を括弧グループへ分ける。グループは空行を落とす「前」に全行で確定する
 * (空行を挟んでも groupWithPrevious の行が前のグループに吸われて AND が OR に化けない
 * ように)。グループ先頭 (空行でも) の connector が前グループとの結合で、グループが空に
 * なったら捨てる。列が空の行は出力に含めない。
 */
function whereGroups(conditions: WhereCondition[]): { connector: "AND" | "OR"; items: WhereCondition[] }[] {
  const groups: { connector: "AND" | "OR"; items: WhereCondition[] }[] = [];
  conditions.forEach((c, i) => {
    const connector = c.connector === "OR" ? "OR" : "AND";
    const last = groups[groups.length - 1];
    if (i > 0 && c.groupWithPrevious === true && last) {
      if (c.column) last.items.push(c);
    } else {
      groups.push({ connector, items: c.column ? [c] : [] });
    }
  });
  return groups.filter((g) => g.items.length > 0);
}

/**
 * 括弧でまとめていない AND と OR が最上位で混在しているか (`a OR b AND c` のように
 * SQL の優先順位 = AND が先、で読まれる並び)。UPDATE / DELETE で意図とずれると
 * 広い範囲を書き換えうるので、UI が注意を出す。
 */
export function hasAmbiguousAndOr(conditions: WhereCondition[]): boolean {
  const live = whereGroups(conditions);
  // グループが 1 つだけだと括弧が付かない (renderWhereClause の wrap) ので、中身の結合子が
  // そのまま最上位に並ぶ。複数グループなら括弧の外 (グループ間) の結合子を見る。
  const joins =
    live.length > 1
      ? live.slice(1).map((g) => g.connector)
      : (live[0]?.items.slice(1).map((c) => (c.connector === "OR" ? "OR" : "AND")) ?? []);
  return joins.includes("AND") && joins.includes("OR");
}

/**
 * WHERE 条件を 1 件消した新しい配列。グループ先頭 (括弧の開始) を消したときは、次の行が
 * 前の行と同じグループに吸われて AND が OR に化けないよう、次の行を新しい先頭へ昇格する
 * (結合子は消した行のものを引き継ぐ)。先頭行を消したときは単に独立させる。
 */
export function removeWhereCondition(prev: WhereCondition[], idx: number): WhereCondition[] {
  const removed = prev[idx];
  const next = prev.filter((_, i) => i !== idx);
  if (removed && !removed.groupWithPrevious && next[idx]?.groupWithPrevious) {
    next[idx] = {
      ...next[idx],
      groupWithPrevious: false,
      connector: idx === 0 ? next[idx].connector : removed.connector,
    };
  } else if (idx === 0 && next[0]?.groupWithPrevious) {
    next[0] = { ...next[0], groupWithPrevious: false };
  }
  return next;
}

/** `removeWhereCondition` のキー付き版 (条件の繋ぎ直しは同じ純ロジックに任せる)。 */
function removeWhereRow<K extends { cond: WhereCondition }>(rows: K[], idx: number): K[] {
  const conds = removeWhereCondition(
    rows.map((r) => r.cond),
    idx,
  );
  return rows.filter((_, i) => i !== idx).map((r, i) => ({ ...r, cond: conds[i] }));
}

/**
 * 行配列に対する安定キー (#2267)。HAVING 行のように ID を持たない配列でも、出入りの
 * アニメーション (`AnimatePresence`) が正しい行を畳めるようにする。長さが同じなら
 * 位置対応 (中身の編集)、変わったら要素の同一性 (filter は参照を保つ) で引き継ぐ。
 */
function useStableKeys<T>(items: T[]): number[] {
  const seq = useRef(items.length);
  const prev = useRef<{ items: T[]; keys: number[] }>({
    items,
    keys: items.map((_, i) => i),
  });
  if (prev.current.items === items) return prev.current.keys;
  const before = prev.current;
  const keys =
    items.length === before.items.length
      ? before.keys
      : items.map((it) => {
          const at = before.items.indexOf(it);
          return at >= 0 ? before.keys[at] : seq.current++;
        });
  prev.current = { items, keys };
  return keys;
}

/**
 * WHERE 条件行の外枠 (#1936)。退場アニメ中の行は古い props のまま残るため、操作を
 * 受け付けないよう `inert` + `pointer-events: none` にする (消えかけの行の × が
 * 見えている別の行を消す事故を防ぐ)。行間の gap は内側 padding で持つ。
 */
function PresenceGuard({ css, children }: { css: SystemStyleObject; children: ReactNode }) {
  const present = useIsPresent();
  return (
    <Box css={css} pt="1.5" inert={!present} pointerEvents={present ? undefined : "none"}>
      {children}
    </Box>
  );
}

