  // 結合 / 集計 / HAVING (SELECT のみ、#2242)。旧スナップショットは `selectColumns` だけを持つので、
  // `restoreJoinFields` が基点の表の素の列として `selectItems` へ読み替える。
  const [restored] = useState(() => restoreJoinFields(initialSnapshot));
  const [selectItems, setSelectItems] = useState<QbSelectItem[]>(restored.selectItems);
  const [aggColumns, setAggColumns] = useState<QbSelectItem[]>(restored.aggColumns);
  const [joins, setJoins] = useState<QbJoin[]>(restored.joins);
  const [having, setHaving] = useState<QbHaving[]>(restored.having);
  const [newSelectCol, setNewSelectCol] = useState("");
  // 「表を追加」の操作面を開いているか。開いたときに外部キーを 1 度だけ取る。
  const [addingJoin, setAddingJoin] = useState(false);
  const [fks, setFks] = useState<ForeignKey[] | null>(null);
  const fkRequested = useRef<string | null>(null);
  // 結合先の表の列情報 (表名 → 列)。基点の表は `tableColumns`。
  const [joinColumns, setJoinColumns] = useState<Record<string, TableColumnInfo[]>>({});
  // WHERE は既定オフ (空の条件のまま「実行」が押せない状態で始めない)。「条件を追加」でオンにする。
  // UPDATE / DELETE に切り替えたときは全行対象を避けるためオンに戻す (下の setKind 参照)。
  const [whereEnabled, setWhereEnabled] = useState(initialSnapshot?.whereEnabled ?? false);
  // 条件行は安定キー付きの 1 つの state で持つ (#1936)。追加/削除の出入りアニメ
  // (`AnimatePresence`) は退場中の行を古い props のまま描画し続けるため、行の操作は
  // index ではなくキーで指す。`whereConditions` (SQL 生成・スナップショット) は
  // そこから導く従来どおりの配列で、キーは混ぜない。
  const [whereRows, setWhereRows] = useState<{ key: number; cond: WhereCondition }[]>(() =>
    (initialSnapshot?.whereConditions ?? [{ column: "", operator: "=", value: "" }]).map((cond, key) => ({
      key,
      cond,
    })),
  );
  const whereKeySeq = useRef(whereRows.length);
  const whereConditions = useMemo(() => whereRows.map((r) => r.cond), [whereRows]);
  // 削除直後にフォーカスを移す先の行キー (null は「+ 条件を追加」)。
  const [pendingFocus, setPendingFocus] = useState<{ key: number | null } | null>(null);
