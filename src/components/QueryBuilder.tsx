      const expandable = tableColumns.filter((c) => !isAutoGenerated(c)).map((c) => c.name);
      const expanded: ColumnValuePair[] = expandable.map((name) => ({
        column: name,
        value: existingByCol.get(name) ?? "",
      }));
      const extra = prev.filter((p) => p.column && !expandable.includes(p.column));
