function deriveSeed(seed: number, salt: number): number {
  return (seed ^ Math.imul(salt + 1, 0x9e3779b1)) >>> 0;
}

/** 列名の FNV-1a ハッシュ (グループのシードを列の並びに依存させない)。 */
function hashName(name: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < name.length; i++) {
    h ^= name.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

function shuffledOrder(n: number, rng: () => number): number[] {
  const order = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

/** 衝突回避のサフィックスを付ける。メールアドレスは `@` の前、宣言長を超えないよう基底を切り詰める。 */
function withSuffix(s: string, k: number, maxLen: number | null): string {
  const suffix = `_${k}`;
  const at = s.lastIndexOf("@");
  if (at > 0) {
    const domain = s.slice(at);
    let local = s.slice(0, at);
    if (maxLen !== null) local = local.slice(0, Math.max(1, maxLen - suffix.length - domain.length));
    return `${local}${suffix}${domain}`;
  }
  const head = maxLen !== null ? s.slice(0, Math.max(1, maxLen - suffix.length)) : s;
  return `${head}${suffix}`;
}

/**
 * 一意制約のある列で、すでに使った値と衝突したら文字列は `_2` 形式 (大小・末尾空白を無視して判定)、
 * 数値は最大値+1 にずらす。基底値ごとに次のサフィックス番号を覚えて計算量を抑える。
 */
function makeUniquifier(maxLen: number | null): (v: CellValue) => CellValue {
  const used = new Set<string>();
  const nextK = new Map<string, number>();
  const norm = (x: string) => x.toLowerCase().trimEnd();
  let maxNum = Number.NEGATIVE_INFINITY;
  return (v) => {
    if (v === null) return v;
    if (typeof v === "number") {
      let n = v;
      if (used.has(String(n))) n = Math.floor(Math.max(maxNum, n)) + 1;
      used.add(String(n));
      maxNum = Math.max(maxNum, n);
      return n;
    }
    const base = String(v);
    const key = norm(base);
    if (!used.has(key)) {
      used.add(key);
      return base;
    }
    for (let k = nextK.get(key) ?? 2; ; k++) {
      const cand = withSuffix(base, k, maxLen);
      if (!used.has(norm(cand))) {
        nextK.set(key, k + 1);
        used.add(norm(cand));
        return cand;
      }
    }
  };
}

function aiColumnValues(
  spec: ColumnGenSpec,
  plan: AiColumnPlan,
  idxs: number[],
  seed: number,
  unique: boolean,
): CellValue[] {
  const nullRng = mulberry32(deriveSeed(seed, 0x4e554c4c));
  const nOffset = deriveSeed(seed, 0x6f66) % PATTERN_OFFSET_RANGE;
  const uniq = unique ? makeUniquifier(declaredLength(spec.dataType)) : null;
  return idxs.map((idx, i) => {
    if (spec.nullRate > 0 && nullRng() < spec.nullRate) return null;
    let raw = plan.choices[idx];
    if (plan.kind === "pattern") raw = raw.replace(/\{n\}/g, String(i + 1 + nOffset));
    const v = coerceFixedValue(raw, spec.kind);
    return uniq ? uniq(v) : v;
  });
}

/**
 * AI の計画から決定的に行を展開する。計画にある列は候補から選び (整合ルールの列は同じ添字)、
 * それ以外はルールベースで生成する。FK 列は取得済みの親の既存値から選ぶ。同じ入力 + シードなら常に同じ結果。
 */
export function generateAiRows(input: AiTableInput, seed: number): AiTableRows {
  const active = activeSpecs(input.specs);
  const unique = new Set(input.uniqueColumns);
  const plan = input.plan;
  const colValues: CellValue[][] = new Array(active.length);

  // AI 値を当てる列 (計画にあり、方針が AI 対象のもの) と、そのグループ。
  const aiIndex = new Map<string, number>();
  active.forEach((s, i) => {
    if (plan && plan.columns[s.column] && isAiEligible(s)) aiIndex.set(s.column, i);
  });
  const groups: string[][] = [];
  const grouped = new Set<string>();
  for (const g of plan?.groups ?? []) {
    const members = g.filter((n) => aiIndex.has(n));
    if (members.length >= 2) {
      groups.push(members);
      for (const n of members) grouped.add(n);
    }
  }
  for (const name of aiIndex.keys()) if (!grouped.has(name)) groups.push([name]);

  for (const members of groups) {
    if (!plan) break;
    const n = plan.columns[members[0]].choices.length;
    const hasUnique = members.some((m) => unique.has(m));
    const rng = mulberry32(deriveSeed(seed, hashName(members[0])));
    const order = hasUnique ? shuffledOrder(n, rng) : null;
    const idxs: number[] = [];
    for (let i = 0; i < input.count; i++) {
      idxs.push(order ? order[i % n] : Math.floor(rng() * n));
    }
    for (const m of members) {
      const ci = aiIndex.get(m) ?? 0;
      colValues[ci] = aiColumnValues(active[ci], plan.columns[m], idxs, deriveSeed(seed, hashName(m)), unique.has(m));
    }
  }

  // それ以外はルールベースの生成 (列ごとに別シードで、他列の増減に影響されない)。
  active.forEach((spec, ci) => {
    if (colValues[ci]) return;
    const col = generateRows([spec], input.count, deriveSeed(seed, 2000 + ci));
    colValues[ci] = col.map((r) => r[0]);
  });

  const rows: CellValue[][] = [];
  for (let i = 0; i < input.count; i++) rows.push(colValues.map((c) => c[i]));
  return { columns: active.map((s) => s.column), rows };
}
