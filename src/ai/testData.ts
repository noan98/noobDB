/** 応答の検証で見つかった注意点 (表示は呼び出し側が i18n する)。 */
export interface TestDataPlanWarning {
  code: "unknownColumn" | "unusableChoices" | "misaligned";
  columns: string[];
}

export interface AiColumnPlan {
  kind: "choices" | "pattern";
  choices: string[];
}

export interface TestDataAiPlan {
  columns: Record<string, AiColumnPlan>;
  /** 行ごとに同じ添字で選ぶ列のグループ (整合ルール)。2 列以上のものだけ。 */
  groups: string[][];
  rules: { columns: string[]; description: string }[];
  notes: Record<string, string>;
  warnings: TestDataPlanWarning[];
}

function isNumericText(s: string): boolean {
  return s.trim() !== "" && Number.isFinite(Number(s.trim()));
}

/** 列の型に使える候補だけを残す。 */
function usableChoices(col: TestDataAiColumn, kind: AiColumnPlan["kind"], raw: string[]): string[] {
  const colKind = classifyDataType(col.dataType);
  let out = raw.map((c) => c.trim()).filter((c) => c !== "");
  if (col.enumChoices && col.enumChoices.length > 0) {
    const allowed = new Set(col.enumChoices);
    out = out.filter((c) => allowed.has(c));
  } else if (colKind === "number" || colKind === "decimal") {
    out = kind === "pattern" ? [] : out.filter(isNumericText);
  } else if (colKind === "bool") {
    out = kind === "pattern" ? [] : out.filter((c) => /^(true|false|0|1)$/i.test(c));
  }
  return out.slice(0, TEST_DATA_MAX_CHOICES);
}

/**
 * 応答を検証して展開用の計画にする。未知の列は捨て、型に合わない候補は除き、
 * 整合ルールは候補の個数が揃っているときだけ「同じ添字で選ぶ」扱いにする。
 */
export function buildTestDataPlan(resp: TestDataAiResponse, columns: TestDataAiColumn[]): TestDataAiPlan {
  const byName = new Map(columns.map((c) => [c.name, c]));
  const plan: TestDataAiPlan = { columns: {}, groups: [], rules: [], notes: {}, warnings: [] };
  const unknown: string[] = [];
  const unusable: string[] = [];
  for (const entry of resp.columns) {
    const col = byName.get(entry.name);
    if (!col) {
      unknown.push(entry.name);
      continue;
    }
    if (entry.notes.trim() !== "") plan.notes[entry.name] = entry.notes.trim();
    if (entry.kind === "skip") continue;
    const choices = usableChoices(col, entry.kind, entry.choices);
    if (choices.length === 0) {
      unusable.push(entry.name);
      continue;
    }
    plan.columns[entry.name] = { kind: entry.kind, choices };
  }
  if (unknown.length > 0) plan.warnings.push({ code: "unknownColumn", columns: unknown });
  if (unusable.length > 0) plan.warnings.push({ code: "unusableChoices", columns: unusable });

  // 整合ルール → 添字を揃える列のグループ (union-find)。
  const parent = new Map<string, string>();
  const find = (x: string): string => {
    let r = x;
    while ((parent.get(r) ?? r) !== r) r = parent.get(r) ?? r;
    return r;
  };
  const misaligned = new Set<string>();
  for (const rule of resp.consistency_rules) {
    const names = [...new Set(rule.columns)].filter((n) => plan.columns[n] !== undefined);
    if (names.length < 2) continue;
    const len = plan.columns[names[0]].choices.length;
    if (names.some((n) => plan.columns[n].choices.length !== len)) {
      for (const n of names) misaligned.add(n);
      continue;
    }
    plan.rules.push({ columns: names, description: rule.description });
    for (const n of names) if (!parent.has(n)) parent.set(n, n);
    for (const n of names.slice(1)) parent.set(find(n), find(names[0]));
  }
  if (misaligned.size > 0) plan.warnings.push({ code: "misaligned", columns: [...misaligned] });
  const groups = new Map<string, string[]>();
  for (const name of parent.keys()) {
    const root = find(name);
    groups.set(root, [...(groups.get(root) ?? []), name]);
  }
  // 別ルールの合流で個数が食い違ったグループは、ばらして独立に選ぶ。
  for (const g of groups.values()) {
    const len = plan.columns[g[0]].choices.length;
    if (g.length >= 2 && g.every((n) => plan.columns[n].choices.length === len)) plan.groups.push(g);
  }
  return plan;
}

/** 1 テーブル分の展開入力。 */
export interface AiTableInput {
  table: string;
  /** `inferColumnSpec` + ユーザ編集後の方針 (FK 候補の取得済み値を含む)。 */
  specs: ColumnGenSpec[];
  plan: TestDataAiPlan | null;
  /** 主キー / UNIQUE 列 (展開時に一意化する)。 */
  uniqueColumns: string[];
  count: number;
}

export interface AiTableRows {
  /** `activeSpecs(specs)` と同じ順の列名。 */
  columns: string[];
  rows: CellValue[][];
}

function deriveSeed(seed: number, salt: number): number {
  return (seed ^ Math.imul(salt + 1, 0x9e3779b1)) >>> 0;
}

function shuffledOrder(n: number, rng: () => number): number[] {
  const order = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

/** 一意制約のある列で、すでに使った値と衝突したら文字列は `_2` 形式、数値は最大値+1 にずらす。 */
function makeUniquifier(): (v: CellValue) => CellValue {
  const used = new Set<string>();
  let maxNum = Number.NEGATIVE_INFINITY;
  return (v) => {
    if (v === null) return v;
    if (typeof v === "number") {
      let n = v;
      if (used.has(String(n))) n = Math.floor(Math.max(maxNum, n)) + 1;
      used.add(String(n));
      maxNum = Math.max(maxNum, n);
      return n;
    }
    const base = String(v);
    let s = base;
    for (let k = 2; used.has(s); k++) s = `${base}_${k}`;
    used.add(s);
    return s;
  };
}

function aiColumnValues(
  spec: ColumnGenSpec,
  plan: AiColumnPlan,
  idxs: number[],
  seed: number,
  unique: boolean,
): CellValue[] {
  const nullRng = mulberry32(deriveSeed(seed, 0x4e554c4c));
  const uniq = unique ? makeUniquifier() : null;
  return idxs.map((idx, i) => {
    if (spec.nullRate > 0 && nullRng() < spec.nullRate) return null;
    let raw = plan.choices[idx];
    if (plan.kind === "pattern") raw = raw.replace(/\{n\}/g, String(i + 1));
    const v = coerceFixedValue(raw, spec.kind);
    return uniq ? uniq(v) : v;
  });
}

function expandTable(
  input: AiTableInput,
  seed: number,
  parentValues: Map<string, CellValue[]>,
): AiTableRows {
  const active = activeSpecs(input.specs).map((spec) => {
    // 親も同時に生成する場合: 取得済みの候補が無い FK 列は親の生成値から配る。
    if (spec.strategy === "fkRef" && spec.choices.length === 0 && spec.fkTable && spec.fkColumn) {
      const vals = parentValues.get(`${spec.fkTable}\u0000${spec.fkColumn}`);
      if (vals) return { ...spec, choices: vals };
    }
    return spec;
  });
  const unique = new Set(input.uniqueColumns);
  const plan = input.plan;
  const colValues: CellValue[][] = new Array(active.length);

  // AI 値を当てる列 (計画にあり、方針が AI 対象のもの) と、そのグループ。
  const aiIndex = new Map<string, number>();
  active.forEach((s, i) => {
    if (plan && plan.columns[s.column] && isAiEligible(s)) aiIndex.set(s.column, i);
  });
  const groups: string[][] = [];
  const grouped = new Set<string>();
  for (const g of plan?.groups ?? []) {
    const members = g.filter((n) => aiIndex.has(n));
    if (members.length >= 2) {
      groups.push(members);
      for (const n of members) grouped.add(n);
    }
  }
  for (const name of aiIndex.keys()) if (!grouped.has(name)) groups.push([name]);

  groups.forEach((members, gi) => {
    if (!plan) return;
    const n = plan.columns[members[0]].choices.length;
    const hasUnique = members.some((m) => unique.has(m));
    const rng = mulberry32(deriveSeed(seed, gi));
    const order = hasUnique ? shuffledOrder(n, rng) : null;
    const idxs: number[] = [];
    for (let i = 0; i < input.count; i++) {
      idxs.push(order ? order[i % n] : Math.floor(rng() * n));
    }
    for (const m of members) {
      const ci = aiIndex.get(m) ?? 0;
      colValues[ci] = aiColumnValues(active[ci], plan.columns[m], idxs, deriveSeed(seed, 1000 + ci), unique.has(m));
    }
  });

  // それ以外はルールベースの生成 (列ごとに別シードで、他列の増減に影響されない)。
  active.forEach((spec, ci) => {
    if (colValues[ci]) return;
    const col = generateRows([spec], input.count, deriveSeed(seed, 2000 + ci));
    colValues[ci] = col.map((r) => r[0]);
  });

  const rows: CellValue[][] = [];
  for (let i = 0; i < input.count; i++) rows.push(colValues.map((c) => c[i]));
  return { columns: active.map((s) => s.column), rows };
}

/**
 * AI の計画から決定的に行を展開する。複数テーブルを渡すと親 → 子の順に生成し、
 * 親の生成値を子の FK 列へ配る (参照が壊れない)。同じ入力 + シードなら常に同じ結果。
 */
export function generateAiDataset(tables: AiTableInput[], seed: number): Record<string, AiTableRows> {
  const names = new Set(tables.map((t) => t.table));
  const done = new Set<string>();
  const ordered: AiTableInput[] = [];
  let remaining = tables.slice();
  while (remaining.length > 0) {
    const ready = remaining.filter((t) =>
      t.specs.every(
        (s) => s.strategy !== "fkRef" || !s.fkTable || s.fkTable === t.table || !names.has(s.fkTable) || done.has(s.fkTable),
      ),
    );
    // 循環参照は先頭を強制的に進める (その FK 列は NULL 生成になる)。
    const next = ready.length > 0 ? ready : [remaining[0]];
    for (const t of next) {
      ordered.push(t);
      done.add(t.table);
    }
    remaining = remaining.filter((t) => !next.includes(t));
  }
  const out: Record<string, AiTableRows> = {};
  const parentValues = new Map<string, CellValue[]>();
  ordered.forEach((input, ti) => {
    const res = expandTable(input, deriveSeed(seed, 3000 + ti), parentValues);
    out[input.table] = res;
    res.columns.forEach((c, ci) => {
      const seen = new Set<string>();
      const vals: CellValue[] = [];
      for (const r of res.rows) {
        const v = r[ci];
        if (v === null || seen.has(String(v))) continue;
        seen.add(String(v));
        vals.push(v);
      }
      parentValues.set(`${input.table}\u0000${c}`, vals);
    });
  });
  return out;
}
