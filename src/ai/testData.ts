/** 方針が「ランダム系 / 列挙」の列にだけ AI の値を当てる (固定値・連番・UUID・参照先・対象外はユーザ指定を優先)。 */
const AI_ELIGIBLE_STRATEGIES = new Set<ColumnGenSpec["strategy"]>([
  "randomString",
  "randomNumber",
  "randomDate",
  "randomBool",
  "choice",
]);

export function isAiEligible(spec: ColumnGenSpec): boolean {
  return AI_ELIGIBLE_STRATEGIES.has(spec.strategy) && spec.kind !== "binary";
}


function isUniqueKey(key: string): boolean {
  const k = key.toUpperCase();
  return k.includes("PRI") || k.includes("UNI");
}

/** `listIndexes` の結果のうち一意判定に使う部分。 */
export interface UniqueIndexLike {
  columns: string[];
  unique: boolean;
  primary: boolean;
}

export interface UniqueColumnInfo {
  /** 単一列で一意な列 (展開時に必ず一意化する)。 */
  columns: string[];
  /** 複合 UNIQUE / 複合主キーの列の組 (展開では保証できないので警告する)。 */
  composite: string[][];
}

/**
 * 一意な列を集める。`describe_table` の `key` は MySQL の `PRI`/`UNI` しか持たず、
 * PostgreSQL / SQLite の UNIQUE index は拾えないので、`listIndexes` の単一列 unique index も足す。
 */
export function resolveUniqueColumns(cols: TableColumnInfo[], indexes: UniqueIndexLike[]): UniqueColumnInfo {
  const set = new Set(cols.filter((c) => isUniqueKey(c.key)).map((c) => c.name));
  const composite: string[][] = [];
  for (const ix of indexes) {
    if (!ix.unique && !ix.primary) continue;
    if (ix.columns.length === 1) set.add(ix.columns[0]);
    else if (ix.columns.length > 1) composite.push(ix.columns);
  }
  return { columns: cols.map((c) => c.name).filter((n) => set.has(n)), composite };
}

/**
 * `describe_table` の結果とユーザの現在の方針から、AI に送る列情報を作る。
 * 自動採番 / 生成列は含めない。デフォルト値・列コメントは読まない。
 */
export function buildTestDataAiContext(
  cols: TableColumnInfo[],
  specs: ColumnGenSpec[],
  hints: Record<string, string>,
  uniqueColumns: string[],
): TestDataAiContext {
  const uniq = new Set(uniqueColumns);
  const columns: TestDataAiColumn[] = [];
  const references: TestDataAiReference[] = [];
  cols.forEach((col, i) => {
    const spec = specs[i];
    if (!spec || spec.strategy === "omit" || isAutoGenerated(col)) return;
    if (col.referenced_table) {
      references.push({ column: col.name, table: col.referenced_table, refColumn: col.referenced_column });
    }
    if (!isAiEligible(spec)) return;
    columns.push({
      name: col.name,
      dataType: col.data_type,
      nullable: col.nullable,
      primaryKey: col.key.toUpperCase().includes("PRI"),
      unique: uniq.has(col.name) || isUniqueKey(col.key),
      enumChoices: parseEnumChoices(col.data_type),
      hint: (hints[col.name] ?? "").trim().replace(/\s+/g, " ").slice(0, TEST_DATA_HINT_MAX),
    });
  });
  return { columns, references };
}

