// テストデータ生成の AI モード (#698) の純ロジック: コンテキスト組み立て・プロンプト・応答パース・決定的な展開。
// 副作用 (IPC・状態管理) は `components/TestDataModal.tsx` が持つ。
//
// ハイブリッド生成でトークンを抑える: AI には「列ごとの値パターン (候補値のリスト) と列間の整合ルール」
// だけを返させ、行への展開は `mulberry32` のシードで決定的にフロントで行う。
// 送るのはテーブル名・列名・型・NULL 可否・キー種別・ENUM 候補・外部キー・件数・ロケール・ユーザが書いたヒントだけで、
// 既存の実データ・サンプル値・デフォルト値・列コメントは送らない。

