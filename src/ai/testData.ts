/** 1 列あたりに AI へ求める候補値 / テンプレートの最大数。 */
export const TEST_DATA_MAX_CHOICES = 50;

/** ヒント 1 行の最大文字数 (長文を送らない)。 */
export const TEST_DATA_HINT_MAX = 200;

/** 構造化出力で受け取る応答の形 (`run_ai_request` の `format` にそのまま渡す)。 */
export const TEST_DATA_FORMAT = {
  type: "json_schema",
  schema: {
    type: "object",
    properties: {
      columns: {
        type: "array",
        items: {
          type: "object",
          properties: {
            name: { type: "string" },
            kind: { type: "string", enum: ["choices", "pattern", "skip"] },
            choices: { type: "array", items: { type: "string" } },
            notes: { type: "string" },
          },
          required: ["name", "kind", "choices", "notes"],
          additionalProperties: false,
        },
      },
      consistency_rules: {
        type: "array",
        items: {
          type: "object",
          properties: {
            columns: { type: "array", items: { type: "string" } },
            description: { type: "string" },
          },
          required: ["columns", "description"],
          additionalProperties: false,
        },
      },
    },
    required: ["columns", "consistency_rules"],
    additionalProperties: false,
  },
} as const;

const responseSchema = z.object({
  columns: z.array(
    z.object({
      name: z.string(),
      kind: z.enum(["choices", "pattern", "skip"]),
      choices: z.array(z.string()),
      notes: z.string(),
    }),
  ),
  consistency_rules: z.array(z.object({ columns: z.array(z.string()), description: z.string() })),
});
export type TestDataAiResponse = z.infer<typeof responseSchema>;

export type ParsedTestDataResponse = { ok: true; value: TestDataAiResponse } | { ok: false; raw: string };

/** ストリームで結合した本文を JSON として解釈する。失敗時は本文をそのまま返す。 */
export function parseTestDataResponse(text: string): ParsedTestDataResponse {
  let body = text.trim();
  const fenced = /^```(?:json)?\s*([\s\S]*?)\s*```$/.exec(body);
  if (fenced) body = fenced[1];
  try {
    const parsed = responseSchema.safeParse(JSON.parse(body));
    if (parsed.success) return { ok: true, value: parsed.data };
  } catch {
    /* JSON でない */
  }
  return { ok: false, raw: text };
}

/** AI に値パターンを作らせる列。 */
export interface TestDataAiColumn {
  name: string;
  dataType: string;
  nullable: boolean;
  primaryKey: boolean;
  unique: boolean;
  /** ENUM / SET の宣言候補 (スキーマ由来)。 */
  enumChoices: string[] | null;
  /** ユーザが任意で書いたヒント (1 行)。 */
  hint: string;
}

/** AI へ「参照先の既存行から埋める」と伝える外部キー列 (生成はさせない)。 */
export interface TestDataAiReference {
  column: string;
  table: string;
  refColumn: string | null;
}

export interface TestDataAiContext {
  columns: TestDataAiColumn[];
  references: TestDataAiReference[];
}

/** 方針が「ランダム系 / 列挙」の列にだけ AI の値を当てる (固定値・連番・UUID・参照先・対象外はユーザ指定を優先)。 */
const AI_ELIGIBLE_STRATEGIES = new Set<ColumnGenSpec["strategy"]>([
  "randomString",
  "randomNumber",
  "randomDate",
  "randomBool",
  "choice",
]);

export function isAiEligible(spec: ColumnGenSpec): boolean {
  return AI_ELIGIBLE_STRATEGIES.has(spec.strategy) && spec.kind !== "binary";
}

function isUniqueKey(key: string): boolean {
  const k = key.toUpperCase();
  return k.includes("PRI") || k.includes("UNI");
}

/** 主キー・UNIQUE 列の名前 (展開時に一意化する)。 */
export function uniqueColumnNames(cols: TableColumnInfo[]): string[] {
  return cols.filter((c) => isUniqueKey(c.key)).map((c) => c.name);
}

/**
 * `describe_table` の結果とユーザの現在の方針から、AI に送る列情報を作る。
 * 自動採番 / 生成列は含めない。デフォルト値・列コメントは読まない。
 */
export function buildTestDataAiContext(
  cols: TableColumnInfo[],
  specs: ColumnGenSpec[],
  hints: Record<string, string>,
): TestDataAiContext {
  const columns: TestDataAiColumn[] = [];
  const references: TestDataAiReference[] = [];
  cols.forEach((col, i) => {
    const spec = specs[i];
    if (!spec || spec.strategy === "omit" || isAutoGenerated(col)) return;
    if (col.referenced_table) {
      references.push({ column: col.name, table: col.referenced_table, refColumn: col.referenced_column });
    }
    if (!isAiEligible(spec)) return;
    columns.push({
      name: col.name,
      dataType: col.data_type,
      nullable: col.nullable,
      primaryKey: col.key.toUpperCase().includes("PRI"),
      unique: isUniqueKey(col.key),
      enumChoices: parseEnumChoices(col.data_type),
      hint: (hints[col.name] ?? "").trim().replace(/\s+/g, " ").slice(0, TEST_DATA_HINT_MAX),
    });
  });
  return { columns, references };
}

export interface TestDataSystemInput {
  driver: string;
  table: string;
  rowCount: number;
  locale: "ja" | "en";
  context: TestDataAiContext;
}

function describeColumn(c: TestDataAiColumn): string {
  const parts = [`- ${c.name}: ${c.dataType}`, c.nullable ? "NULL" : "NOT NULL"];
  if (c.primaryKey) parts.push("PRIMARY KEY");
  else if (c.unique) parts.push("UNIQUE");
  let line = parts.join(" ");
  if (c.enumChoices && c.enumChoices.length > 0) {
    line += ` | allowed values: ${c.enumChoices.join(" / ")}`;
  }
  if (c.hint !== "") line += ` | user hint: ${c.hint}`;
  return line;
}

/** system プロンプト。スキーマ・件数・ロケールだけを含み、行データは含めない。 */
export function buildTestDataSystem(input: TestDataSystemInput): string {
  const lang = input.locale === "ja" ? "Japanese" : "English";
  const dialect = dialectLabel(input.driver);
  const lines = [
    `You design realistic test data for a ${dialect} table, using only its schema.`,
    `The caller will insert about ${input.rowCount} rows. You do NOT write rows: you return, per column, a compact list of realistic values or templates, and the caller expands them into rows.`,
    `Write human-readable values (names, addresses, product names, statuses, free text) in ${lang}, appropriate for the column names and the user hints. Write notes in ${lang}.`,
    "Answer only with the JSON object described by the schema.",
    `columns: one entry per column listed below, using the exact column name. kind "choices": up to ${TEST_DATA_MAX_CHOICES} distinct realistic values. kind "pattern": up to ${TEST_DATA_MAX_CHOICES} templates in which {n} is replaced by the 1-based row number (use for emails, codes, order numbers). kind "skip": the column cannot be meaningfully generated, so leave it to a generic generator (choices: []). notes: a short remark, or an empty string.`,
    "Every value is a string. Numbers are plain digits (no thousands separators or units), booleans are true/false, dates are YYYY-MM-DD, date-times are YYYY-MM-DD HH:MM:SS, times are HH:MM:SS. Respect the declared type, length and NOT NULL.",
    "For columns with allowed values, use only those values.",
    'consistency_rules: groups of columns whose values must correspond row by row (for example product_name and unit_price, or country and city). For every column in one rule, return "choices" lists of exactly the same length where the i-th entry of each list belongs to the same logical record. Columns that are not in any rule are independent. Use an empty array when there are no such relations.',
    "Use only the listed columns; never invent names. You are given only the schema: you never see real rows, so do not assume or reproduce any existing data.",
    "",
    `Table: ${input.table}`,
    "Columns to design:",
    ...input.context.columns.map(describeColumn),
  ];
  if (input.context.references.length > 0) {
    lines.push("");
    lines.push("Foreign key columns (filled by the caller from existing parent rows; do not design them):");
    for (const r of input.context.references) {
      lines.push(`- ${r.column} -> ${r.table}.${r.refColumn ?? "?"}`);
    }
  }
  return lines.join("\n");
}

