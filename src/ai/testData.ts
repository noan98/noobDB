/** `{n}` の置換後の長さを見積もるときの桁数 (行番号 + 開始オフセットの最大桁)。 */
const PATTERN_DIGITS = 6;
/** `{n}` の開始値オフセットの上限 (同じテーブルへ再投入しても衝突しにくくする)。 */
const PATTERN_OFFSET_RANGE = 100000;

function validDate(y: number, m: number, d: number): boolean {
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d;
}

function validTime(h: number, mi: number, sec: number): boolean {
  return h <= 23 && mi <= 59 && sec <= 59;
}

/** `YYYY-MM-DD` / `HH:MM:SS` / `YYYY-MM-DD HH:MM:SS` を書式どおりかつ実在する日時か確認する。 */
export function isValidTemporal(s: string, format: TemporalFormat): boolean {
  const dateRe = "(\\d{4})-(\\d{2})-(\\d{2})";
  const timeRe = "(\\d{2}):(\\d{2}):(\\d{2})";
  if (format === "date") {
    const m = new RegExp(`^${dateRe}$`).exec(s);
    return !!m && validDate(+m[1], +m[2], +m[3]);
  }
  if (format === "time") {
    const m = new RegExp(`^${timeRe}$`).exec(s);
    return !!m && validTime(+m[1], +m[2], +m[3]);
  }
  const m = new RegExp(`^${dateRe} ${timeRe}$`).exec(s);
  return !!m && validDate(+m[1], +m[2], +m[3]) && validTime(+m[4], +m[5], +m[6]);
}

/** その列に入れてよい 1 値か。投入トランザクションごと失敗しうる値を事前に落とす。 */
function isUsableValue(col: TestDataAiColumn, kind: AiColumnPlan["kind"], raw: string): boolean {
  const v = raw.trim();
  if (v === "" || /^null$/i.test(v)) return false;
  const colKind = classifyDataType(col.dataType);
  if (col.enumChoices && col.enumChoices.length > 0) {
    return kind === "choices" && col.enumChoices.includes(v);
  }
  switch (colKind) {
    case "number":
      return kind === "choices" && Number.isInteger(Number(v)) && /^[-+]?\d+$/.test(v);
    case "decimal":
      return kind === "choices" && Number.isFinite(Number(v));
    case "bool":
      return kind === "choices" && /^(true|false|0|1)$/i.test(v);
    case "date":
    case "time":
      return kind === "choices" && isValidTemporal(v, temporalFormatOf(col.dataType));
    default: {
      const max = declaredLength(col.dataType);
      if (max === null) return true;
      const sample = kind === "pattern" ? v.replace(/\{n\}/g, "0".repeat(PATTERN_DIGITS)) : v;
      return sample.length <= max;
    }
  }
}

/**
 * 応答を検証して展開用の計画にする。未知の列は捨て、型・長さに合わない候補は除く。
 * 整合ルールの列は加工前の個数が揃っているときだけ「同じ添字で選ぶ」扱いにし、
 * 全メンバーで有効な添字だけを残す (列ごとに別々に除外して添字がずれるのを防ぐ)。
 */
export function buildTestDataPlan(resp: TestDataAiResponse, columns: TestDataAiColumn[]): TestDataAiPlan {
  const byName = new Map(columns.map((c) => [c.name, c]));
  const plan: TestDataAiPlan = { columns: {}, groups: [], rules: [], notes: {}, warnings: [] };
  const unknown: string[] = [];
  const unusable: string[] = [];
  const raws = new Map<string, { kind: AiColumnPlan["kind"]; raw: string[] }>();
  for (const entry of resp.columns) {
    if (!byName.has(entry.name)) {
      unknown.push(entry.name);
      continue;
    }
    if (entry.notes.trim() !== "") plan.notes[entry.name] = entry.notes.trim();
    if (entry.kind === "skip") continue;
    raws.set(entry.name, { kind: entry.kind, raw: entry.choices });
  }

  // 整合ルール → 添字を揃える列のグループ (union-find)。加工前の個数で判定する。
  const parent = new Map<string, string>();
  const find = (x: string): string => {
    let r = x;
    while ((parent.get(r) ?? r) !== r) r = parent.get(r) ?? r;
    return r;
  };
  const misaligned = new Set<string>();
  const acceptedRules: { columns: string[]; description: string }[] = [];
  for (const rule of resp.consistency_rules) {
    const names = [...new Set(rule.columns)].filter((n) => raws.has(n));
    if (names.length < 2) continue;
    const len = (raws.get(names[0])?.raw ?? []).length;
    if (names.some((n) => (raws.get(n)?.raw ?? []).length !== len)) {
      for (const n of names) misaligned.add(n);
      continue;
    }
    acceptedRules.push({ columns: names, description: rule.description });
    for (const n of names) if (!parent.has(n)) parent.set(n, n);
    for (const n of names.slice(1)) parent.set(find(n), find(names[0]));
  }
  const groupMap = new Map<string, string[]>();
  for (const name of parent.keys()) {
    const root = find(name);
    groupMap.set(root, [...(groupMap.get(root) ?? []), name]);
  }
  const grouped = new Set<string>();
  const groups: string[][] = [];
  for (const g of groupMap.values()) {
    const len = (raws.get(g[0])?.raw ?? []).length;
    // 別ルールの合流で個数が食い違ったグループは、ばらして独立に扱う。
    if (g.length >= 2 && g.every((n) => (raws.get(n)?.raw ?? []).length === len)) {
      groups.push(g);
      for (const n of g) grouped.add(n);
    } else {
      for (const n of g) misaligned.add(n);
    }
  }

  // グループ: 全メンバーで有効な添字の共通部分だけを残す (先頭から TEST_DATA_MAX_CHOICES 件)。
  for (const g of groups) {
    const len = (raws.get(g[0])?.raw ?? []).length;
    const keep: number[] = [];
    for (let i = 0; i < len && keep.length < TEST_DATA_MAX_CHOICES; i++) {
      const ok = g.every((n) => {
        const r = raws.get(n);
        const col = byName.get(n);
        return !!r && !!col && isUsableValue(col, r.kind, r.raw[i]);
      });
      if (ok) keep.push(i);
    }
    if (keep.length === 0) {
      unusable.push(...g);
      continue;
    }
    for (const n of g) {
      const r = raws.get(n);
      if (r) plan.columns[n] = { kind: r.kind, choices: keep.map((i) => r.raw[i].trim()) };
    }
    plan.groups.push(g);
  }
  // ルール外の列は列単位で絞る。
  for (const [name, r] of raws) {
    if (grouped.has(name)) continue;
    const col = byName.get(name);
    if (!col) continue;
    const choices = r.raw
      .filter((c) => isUsableValue(col, r.kind, c))
      .map((c) => c.trim())
      .slice(0, TEST_DATA_MAX_CHOICES);
    if (choices.length === 0) unusable.push(name);
    else plan.columns[name] = { kind: r.kind, choices };
  }
  plan.rules = acceptedRules.filter((r) => r.columns.every((n) => plan.columns[n] !== undefined));
  if (unknown.length > 0) plan.warnings.push({ code: "unknownColumn", columns: unknown });
  if (unusable.length > 0) plan.warnings.push({ code: "unusableChoices", columns: unusable });
  if (misaligned.size > 0) plan.warnings.push({ code: "misaligned", columns: [...misaligned] });
  return plan;
}

